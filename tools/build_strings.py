#!/usr/bin/env python3
"""Builds the String Catalogs from tools/i18n/*.json:
   Shared/Localizable.xcstrings (app, watch, widgets) and Shared/InfoPlist.xcstrings (permission texts),
   plus website/i18n.js.   Run: python3 tools/build_strings.py"""
import glob, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I18N = os.path.join(ROOT, "tools", "i18n")
src = json.load(open(os.path.join(I18N, "source.json")))
langs = {}
for p in sorted(glob.glob(os.path.join(I18N, "*.json"))):
    code = os.path.basename(p)[:-5]
    if code in ("source", "keys"):
        continue
    langs[code] = json.load(open(p))

def unit(v):
    return {"stringUnit": {"state": "translated", "value": v}}

strings = {}
for key in src["app"]:
    locs = {code: unit(d["app"][key]) for code, d in langs.items() if d.get("app", {}).get(key)}
    strings[key] = {"extractionState": "manual", "localizations": locs} if locs else {"extractionState": "manual"}
json.dump({"sourceLanguage": "en", "strings": strings, "version": "1.0"},
          open(os.path.join(ROOT, "Shared", "Localizable.xcstrings"), "w"), indent=2, ensure_ascii=False, sort_keys=True)

cal_txt, loc_txt = src["plist"]
plist_keys = {
    "NSCalendarsFullAccessUsageDescription": cal_txt,
    "NSCalendarsUsageDescription": cal_txt,
    "NSLocationWhenInUseUsageDescription": loc_txt,
    "NSLocationUsageDescription": loc_txt,
}
pstrings = {"CFBundleDisplayName": {"extractionState": "manual", "localizations": {"en": unit("Sevn")}}}
for k, en in plist_keys.items():
    locs = {"en": unit(en)}
    for code, d in langs.items():
        v = d.get("plist", {}).get(en)
        if v:
            locs[code] = unit(v)
    pstrings[k] = {"extractionState": "manual", "localizations": locs}
json.dump({"sourceLanguage": "en", "strings": pstrings, "version": "1.0"},
          open(os.path.join(ROOT, "Shared", "InfoPlist.xcstrings"), "w"), indent=2, ensure_ascii=False, sort_keys=True)

web = {"en": src["web"]}
for code, d in langs.items():
    if d.get("web"):
        web[code] = {k: d["web"].get(k, v) for k, v in src["web"].items()}
os.makedirs(os.path.join(ROOT, "website"), exist_ok=True)
with open(os.path.join(ROOT, "website", "i18n.js"), "w") as f:
    f.write("// Generated by tools/build_strings.py — do not edit by hand.\nwindow.SEVN_I18N = ")
    json.dump(web, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print("languages:", ", ".join(["en"] + sorted(langs)))
